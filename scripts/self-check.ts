import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import solc from "solc";
import {
  evaluateCrossPairStrategy,
  getEpochTimingState,
  optimizeDualVoterPortfolio,
  solveOptimalVoteAllocation,
  type GaugeOpportunity,
} from "../src/lib/optimizer.ts";
import {
  fetchLiveProtocolTelemetry,
  inspectOnChainPosition,
} from "../src/lib/indexer.ts";

async function main() {
  console.log("=== [1/5] Compiling contracts/EpochPilotRouter.sol via solc ===");
  const contractPath = path.join(
    process.cwd(),
    "contracts",
    "EpochPilotRouter.sol"
  );
  const source = fs.readFileSync(contractPath, "utf8");

  const input = {
    language: "Solidity",
    sources: {
      "EpochPilotRouter.sol": { content: source },
    },
    settings: {
      viaIR: true,
      optimizer: { enabled: true, runs: 200 },
      outputSelection: {
        "*": {
          "*": ["abi", "evm.bytecode.object"],
        },
      },
    },
  };

  const output = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (output.errors ?? []).filter(
    (e: { severity: string }) => e.severity === "error"
  );
  assert.equal(
    errors.length,
    0,
    `Solidity compilation failed: ${JSON.stringify(errors, null, 2)}`
  );

  const compiled = output.contracts["EpochPilotRouter.sol"]["EpochPilotRouter"];
  const bytecode = `0x${compiled.evm.bytecode.object}`;
  assert.ok(bytecode.length > 200, "Compiled bytecode should be non-empty");

  // Persist compiled ABI & Bytecode to src/lib/routerArtifact.ts for 1-click UI deployment
  const artifactTs = `// Auto-generated by scripts/self-check.ts from contracts/EpochPilotRouter.sol
export const EPOCH_PILOT_ROUTER_BYTECODE = "${bytecode}" as const;
export const EPOCH_PILOT_ROUTER_COMPILED_ABI = ${JSON.stringify(
    compiled.abi,
    null,
    2
  )} as const;
`;
  fs.writeFileSync(
    path.join(process.cwd(), "src", "lib", "routerArtifact.ts"),
    artifactTs,
    "utf8"
  );
  console.log(
    `✓ EpochPilotRouter.sol compiled cleanly (${
      (bytecode.length - 2) / 2
    } bytes) -> src/lib/routerArtifact.ts`
  );

  console.log("\n=== [2/5] Verifying KKT Water-Filling Optimizer & Marginal Equalization ===");
  const testGauges: GaugeOpportunity[] = [
    {
      id: "g1",
      voterType: "boost",
      gaugeAddress: "0x0000000000000000000000000000000000000001",
      bribeAddress: "0x0000000000000000000000000000000000000011",
      voteTargetAddress: "0x0000000000000000000000000000000000000001",
      label: "Gauge Alpha (High Headline APR, Small Depth)",
      sublabel: "Test",
      chainLabel: "Mezo",
      currentVotes: 50_000,
      totalBribeUsd: 500, // $10 per 1k votes pre-dilution
      bribeTokens: [],
      isAlive: true,
      musdIntegrated: true,
    },
    {
      id: "g2",
      voterType: "boost",
      gaugeAddress: "0x0000000000000000000000000000000000000002",
      bribeAddress: "0x0000000000000000000000000000000000000012",
      voteTargetAddress: "0x0000000000000000000000000000000000000002",
      label: "Gauge Beta (Medium APR, Deep Pool)",
      sublabel: "Test",
      chainLabel: "Mezo",
      currentVotes: 400_000,
      totalBribeUsd: 2_400, // $6 per 1k votes pre-dilution
      bribeTokens: [],
      isAlive: true,
      musdIntegrated: true,
    },
    {
      id: "g3",
      voterType: "boost",
      gaugeAddress: "0x0000000000000000000000000000000000000003",
      bribeAddress: "0x0000000000000000000000000000000000000013",
      voteTargetAddress: "0x0000000000000000000000000000000000000003",
      label: "Gauge Gamma (Moderate APR, Medium Pool)",
      sublabel: "Test",
      chainLabel: "Mezo",
      currentVotes: 150_000,
      totalBribeUsd: 900, // $6 per 1k votes pre-dilution
      bribeTokens: [],
      isAlive: true,
      musdIntegrated: true,
    },
  ];

  const userVoteWeight = 350_000;
  const kkt = solveOptimalVoteAllocation(testGauges, userVoteWeight, "boost");

  // 1) Weights must sum to 10,000 bps
  const bpsSum = kkt.allocations.reduce((s, a) => s + a.weightBps, 0);
  assert.equal(bpsSum, 10_000, "Allocated basis points must sum to 10,000");

  // 2) KKT payout must strictly beat Naive Single-Gauge (which dumps 350k into 50k Gauge Alpha and self-dilutes)
  assert.ok(
    kkt.totalExpectedPayoutUsd > kkt.naiveSingleGaugePayoutUsd,
    `KKT (${kkt.totalExpectedPayoutUsd}) must strictly beat Naive Single-Gauge (${kkt.naiveSingleGaugePayoutUsd})`
  );
  assert.ok(
    kkt.selfDilutionSavedUsd > 400,
    `Expected >$400 saved from self-dilution, got $${kkt.selfDilutionSavedUsd.toFixed(2)}`
  );

  // 3) Marginal returns dR_i/dv_i across all active gauges must be equalized (KKT first-order optimality)
  const marginals = kkt.allocations.map((a) => a.marginalYieldPer10kVeMezo);
  const maxMarginal = Math.max(...marginals);
  const minMarginal = Math.min(...marginals);
  assert.ok(
    Math.abs(maxMarginal - minMarginal) < 1e-2,
    `Marginal yields must be equalized across active gauges: ${marginals.join(", ")}`
  );
  console.log(
    `✓ KKT Solver optimal: $${kkt.totalExpectedPayoutUsd.toFixed(
      2
    )} vs Naive $${kkt.naiveSingleGaugePayoutUsd.toFixed(
      2
    )} (+$${kkt.selfDilutionSavedUsd.toFixed(2)} / epoch saved, marginal=$${marginals[0].toFixed(
      4
    )}/10k)`
  );

  console.log("\n=== [3/5] Verifying Cross-Pair vs. Self-Pair Boost Math ===");
  const crossPair = evaluateCrossPairStrategy({
    veBtcBalance: 2.5,
    veMezoBalance: 450_000,
    totalVeBtcUnboosted: 647.84,
    totalVeMezoSupply: 98_740_000,
    baseWeeklyYieldPerVeBtcUsd: 42,
    externalOptimalVeMezoWeeklyYieldUsd: 690,
    marketBribeCostPer1kVeMezoUsd: 0.72,
  });

  // veMezoNeededFor5x = totalVeMezo * (veBtc / totalVeBtc) — exact BoostLibrary.sol invariant
  const expectedNeeded = crossPair.totalVeMezoSupply * (2.5 / crossPair.totalVeBtcUnboosted);
  assert.ok(
    Math.abs(crossPair.veMezoNeededFor5x - expectedNeeded) / Math.max(expectedNeeded, 1) < 0.001,
    `Unexpected veMezoNeededFor5x: ${crossPair.veMezoNeededFor5x} (expected ~${expectedNeeded.toFixed(1)})`
  );
  assert.equal(crossPair.selfPairBoostMultiplier, 5.0);
  assert.equal(crossPair.recommendedStrategy, "CROSS-PAIR");
  console.log(
    `✓ Cross-Pair Math verified: 5x boost needs ${Math.round(
      crossPair.veMezoNeededFor5x
    ).toLocaleString()} veMEZO | Cross-Pair Net: $${crossPair.crossPair.netWeeklyYieldUsd.toFixed(
      2
    )}/wk vs Self-Pair Net: $${crossPair.selfPair.netWeeklyYieldUsd.toFixed(2)}/wk`
  );

  console.log("\n=== [4/5] Verifying ProtocolTimeLibrary Epoch Window Guard ===");
  const epochBase = Math.floor(1792454400 / 604800) * 604800; // Exact Thursday 00:00 UTC
  const thu0030 = epochBase + 1800; // 30 mins after Thursday 00:00 UTC
  assert.equal(getEpochTimingState(thu0030).windowStatus, "DISTRIBUTE_LOCKED");
  const wed2330 = epochBase + 604800 - 1800; // 30 mins before next Thursday 00:00 UTC
  assert.equal(
    getEpochTimingState(wed2330).windowStatus,
    "SPECIAL_WINDOW_LOCKED"
  );
  console.log("✓ Epoch window states (DISTRIBUTE_LOCKED / OPTIMAL_SNIPE_WINDOW / SPECIAL_WINDOW_LOCKED) verified");

  console.log("\n=== [5/5] Verifying Live Mezo Mainnet (31612) Multicall3 Indexer ===");
  const telemetry = await fetchLiveProtocolTelemetry("mainnet", true);
  assert.equal(telemetry.chainId, 31612);
  assert.ok(
    telemetry.veMezoLockedTotal > 100_000_000,
    `Expected >100M locked MEZO on Mainnet, got ${telemetry.veMezoLockedTotal}`
  );
  assert.ok(
    telemetry.boostVoterGaugeCount >= 700,
    `Expected >=700 BoostVoter gauges on Mainnet, got ${telemetry.boostVoterGaugeCount}`
  );
  assert.ok(
    telemetry.thirdPartyVoterGaugeCount >= 4,
    `Expected >=4 ThirdPartyVoter gauges on Mainnet, got ${telemetry.thirdPartyVoterGaugeCount}`
  );

  const dualOpt = optimizeDualVoterPortfolio(telemetry.gauges, 500_000);
  assert.ok(dualOpt.boostResult.allocations.length > 0);
  assert.ok(dualOpt.thirdPartyResult.allocations.length > 0);

  const pos = await inspectOnChainPosition("mainnet", 12, 8);
  assert.equal(pos.veMezoTokenId, 12);

  console.log(
    `✓ Live Mezo Mainnet Block #${telemetry.blockNumber.toLocaleString()}:`
  );
  console.log(
    `  - Locked MEZO: ${Math.round(
      telemetry.veMezoLockedTotal
    ).toLocaleString()} MEZO (${Math.round(
      telemetry.veMezoTotalVotingPower
    ).toLocaleString()} veMEZO voting power)`
  );
  console.log(
    `  - BoostVoter Utilization: ${telemetry.boostUtilizationPercent.toFixed(
      1
    )}% across ${telemetry.boostVoterGaugeCount} gauges`
  );
  console.log(
    `  - ThirdPartyVoter (MUSD Gauges) Utilization: ${telemetry.thirdPartyUtilizationPercent.toFixed(
      1
    )}% across ${telemetry.thirdPartyVoterGaugeCount} gauges`
  );
  console.log(
    `  - Dual-Voter 500k veMEZO Optimal Weekly Yield: $${dualOpt.combinedWeeklyPayoutUsd.toFixed(
      2
    )} (${dualOpt.combinedAprPercent.toFixed(1)}% APR)`
  );
  console.log("\nALL 5 EPOCHPILOT SELF-CHECKS PASSED.");
}

main().catch((err) => {
  console.error("SELF-CHECK FAILED:", err);
  process.exit(1);
});
